"""rail — ဘေးဘောင် စာရင်း test

⚠️ ကိန်းတိုင်းကို reference `HJ0K1yAuGLw` ၄၀s ရဲ့ full-res ဖရိန်ကနေ
   တိုင်းယူထားသည် (`docs/HEADTALK_STYLE.md` §၅)。
⚠️ rail က **မိနစ်ချီ ဆက်ပေါ်**နေသည် ⇒ မှားလျှင် ဗီဒီယိုတစ်ခုလုံး မှားသည်。
   ⇒ detector က **မသေချာလျှင် မလုပ်ရ**。
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "core"))

import rail as RL      # noqa: E402

FAILED = []


def check(name, cond, detail=""):
    if cond:
        print(f"  ✓ {name}")
    else:
        FAILED.append(name)
        print(f"  ✗ {name}  {detail}")


def S(*t):
    return [dict(start=i * 4.0, end=i * 4.0 + 3.6, text=x)
            for i, x in enumerate(t)]


FULL = S("ဒီနေ့ မတူညီတဲ့ မိသားစု (၅) မျိုး အကြောင်း ပြောပါမယ်",
         "ပထမ တစ်မျိုးကတော့ ဖျက်ဆီးတတ်တဲ့ မိသားစုပါ",
         "အဲဒီမှာ ပြဿနာတွေ များတယ်",
         "ဒုတိယ ကတော့ ရိုက်သိမ်းတဲ့ မိသားစုပါ",
         "တတိယ ကတော့ နှစ်သိမ့်အားပေးတဲ့ မိသားစု",
         "စတုတ္ထ ကတော့ စိတ်တညီတည်း နေတဲ့ မိသားစု",
         "ပဉ္စမ ကတော့ မီးပြတိုက်လို မိသားစုပါ")


def main():
    print("── ၁ · တိုင်းထားသော ဘောင် ──")
    check("pill အကျယ် ၃၀.၄%W", abs(RL.PILL_W - 0.304) < 1e-6, RL.PILL_W)
    check("pill အမြင့် ၁၀.၄%H", abs(RL.PILL_H - 0.104) < 1e-6, RL.PILL_H)
    check("pitch ၁၃.၁၅%H", abs(RL.PITCH - 0.1315) < 1e-6, RL.PITCH)
    check("ဘယ်အနား ၁၀.၉%W", abs(RL.PILL_X - 0.109) < 1e-6, RL.PILL_X)
    check("ပထမ pill ၂၇.၆%H", abs(RL.PILL_Y0 - 0.276) < 1e-6, RL.PILL_Y0)
    # ⚠️ တိုင်းချက်မှာ ၅ ခု ဆံ့ပြီး အောက်စွန်း ၉၀.၆%
    check("၅ ခု ဆံ့သည်", RL.fits(5))
    # ⚠️ တိုင်းချက်မှာ ၅ ခုက ၂၇.၆→၉၀.၆% ဖြည့်သည် ⇒ pitch ၁၃.၁၅% နဲ့
    #    **၅ ခုက အများဆုံး**。 ၆ ခုဆိုလျှင် ၁၀၃.၈% ⇒ ဘောင် ကျော်မည်。
    check("၆ ခု မဆံ့ပါ", not RL.fits(6),
          RL.PILL_Y0 + 5 * RL.PITCH + RL.PILL_H)

    print("\n── ၂ · စာရင်း ရှာခြင်း — တွေ့ရမည် ──")
    for nm, segs, n in (
            ("မြန်မာ ဂဏန်း (၅)", FULL, 5),
            ("ဂဏန်း + ၁။၂။၃။",
             S("အဆင့် ၃ ဆင့် ရှိပါတယ်", "၁။ အရင်ဆုံး ပြင်ဆင်ပါ",
               "၂။ ပြီးရင် လျှောက်ပါ", "၃။ နောက်ဆုံး စောင့်ပါ"), 3),
            ("ရေတွက်စကားလုံး",
             S("နည်းလမ်း သုံးခု ရှိတယ်", "ပထမ နည်းလမ်း", "ဒုတိယ နည်းလမ်း",
               "တတိယ နည်းလမ်း"), 3)):
        r = RL.find(segs)
        check(f"{nm} ⇒ {n} ခု", r is not None and r[2] == n, r)

    print("\n── ၃ · မသေချာလျှင် မလုပ်ရ ──")
    # ⚠️ ဒါက အရေးကြီးဆုံး — မှားလုပ်တာက မလုပ်တာထက် ဆိုးသည်
    for nm, segs in (
            ("ကြေညာရုံ · item မရှိ",
             S("မိသားစု (၅) မျိုး ရှိပါတယ်", "ဒါပေမယ့် တခြားအကြောင်း ပြောမယ်",
               "ဒီနေ့ ရာသီဥတု ကောင်းတယ်")),
            ("item ၁ ခုသာ",
             S("နည်းလမ်း ၃ ခု ရှိတယ်", "ပထမ နည်းလမ်း", "ပြီးတော့ ဘာမှ မပြော")),
            ("များလွန်း (၁၂)",
             S("အချက် ၁၂ ချက် ရှိတယ်", "ပထမ ချက်", "ဒုတိယ ချက်")),
            ("စာရင်း မဟုတ်",
             S("ကျွန်တော် ဂျပန်မှာ နေပါတယ်", "အလုပ်က ခက်တယ်", "ဒါပေမယ့် ပျော်တယ်")),
            ("ဗလာ", [])):
        check(f"{nm} ⇒ မလုပ်ပါ", RL.find(segs) is None, RL.find(segs))

    print("\n── ၄ · item အစ ရှာခြင်း ──")
    r = RL.find(FULL)
    st = RL.starts(FULL, r[0] + 1, r[2])
    check("item ၅ ခုလုံး တွေ့သည်", len(st) == 5, st)
    check("အစဉ်လိုက် တိုးသည်",
          all(st[k] < st[k + 1] for k in range(1, 5)), st)
    check("ကြေညာဝါကျ ပြီးမှ", min(st.values()) > r[0], (r[0], st))

    print("\n── ၅ · ခေါင်းစဉ် ──")
    # ⚠️ စာလုံးအလယ် ပြတ်လျှင် မြန်မာစာ ပျက်သည်
    h = r[1]
    check("ခေါင်းစဉ် ရသည်", bool(h), h)
    check("၄၂ လုံး မကျော်", len(h) <= 42, len(h))
    check("စာလုံးအလယ် မပြတ်ပါ",
          FULL[0]["text"].startswith(h) is False or
          len(h) == len(FULL[0]["text"]) or
          FULL[0]["text"][len(h)] in " ", repr(h))

    print("\n── ၅ခ · မြန်မာစာ ဘေးကင်းမှု ──")
    # ⚠️ `strip(" ကတော့မှာ")` က အက္ခရာ **အစုလိုက်** ဖြတ်သဖြင့်
    #    「ကိုယ့်ဘက်က」→「ိုယ့်ဘက်」ဖြစ်ခဲ့သည် (၂၀၂၆-၀၉-၂၁ · ၂ ကြိမ် ဖမ်းမိ)
    check("「ကိုယ့်」ရဲ့ 「က」 မစားရ",
          RL._drop_pre("ကိုယ့်ဘက်က အထက်တန်း") == "ကိုယ့်ဘက်က အထက်တန်း",
          RL._drop_pre("ကိုယ့်ဘက်က အထက်တန်း"))
    check("space နဲ့ ခွဲထားမှ ဖြုတ်သည်",
          RL._drop_pre("ကတော့ နှစ်သိမ့်") == "နှစ်သိမ့်",
          RL._drop_pre("ကတော့ နှစ်သိမ့်"))
    check("cut_at_space — space မှာသာ",
          RL.cut_at_space("COE စိတ်ချရတဲ့ Class 1 ကျောင်း", 20).endswith("Class"),
          RL.cut_at_space("COE စိတ်ချရတဲ့ Class 1 ကျောင်း", 20))
    check("cut_at_space — တိုလျှင် မထိ",
          RL.cut_at_space("တိုတို", 20) == "တိုတို")
    # ⚠️ 「နံပါတ် ၁」ရှေ့ဆက် ဖယ်ရမည် — မဖယ်လျှင် pill တိုင်း တူသွားမည်
    check("「နံပါတ် ၁」 ဖယ်သည်",
          RL._strip_mark("နံပါတ် ၁ COE စိတ်ချရတဲ့") == "COE စိတ်ချရတဲ့",
          RL._strip_mark("နံပါတ် ၁ COE စိတ်ချရတဲ့"))
    check("「၂။」 ဖယ်သည်",
          RL._strip_mark("၂။ ပြီးရင် လျှောက်ပါ") == "ပြီးရင် လျှောက်ပါ",
          RL._strip_mark("၂။ ပြီးရင် လျှောက်ပါ"))
    # ⚠️ ကြေညာချက်က ဝါကျရဲ့ ဒုတိယပိုင်းမှာ ရှိတတ်သည်
    check("ရေတွက်ချက် ပါသော အပိုင်းကို ယူသည်",
          RL._clause("ဒါပေမဲ့ မရပါဘူး။ အဓိက သော့ချက် ၃ ချက် ရှိပါတယ်။")
          .startswith("အဓိက"),
          RL._clause("ဒါပေမဲ့ မရပါဘူး။ အဓိက သော့ချက် ၃ ချက် ရှိပါတယ်။"))

    print("\n── ၅ဂ · တကယ့် transcript (tokutei) ──")
    # ⚠️ 「နံပါတ် ၁/၂/၃」က **တကယ့် ဒေတာထဲက** အသုံးအများဆုံး ပုံစံ
    real = S("ဒါပေမဲ့ ဒီအတိုင်းတော့ မရပါဘူး။ အဓိက သော့ချက် ၃ ချက် ရှိပါတယ်။",
             "နံပါတ် ၁ COE စိတ်ချရတဲ့ Class 1 ကျောင်း ဖြစ်ရပါမယ်။",
             "ဒါမှ ဗီဇာ ရဖို့ သေချာတာပါ။ နံပါတ် ၂",
             "ဂျပန်ရောက်တဲ့အထိ တာဝန်ယူပေးတဲ့ အေဂျင်စီ ရွေးရပါမယ်။",
             "နံပါတ် ၃ ကိုယ့်ဘက်က အောင်လက်မှတ် ရှိထားရပါမယ်။")
    rr = RL.find(real)
    check("တကယ့် ပုံစံ တွေ့သည်", rr is not None and rr[2] == 3, rr)
    if rr:
        check("ခေါင်းစဉ်က ရေတွက်ချက် အပိုင်း",
              rr[1].startswith("အဓိက"), rr[1])
        rst = RL.starts(real, rr[0] + 1, rr[2])
        check("item ၃ ခုလုံး", len(rst) == 3, rst)
        # ⚠️ 「… နံပါတ် ၂」က ဝါကျအဆုံးမှာ ⇒ item က **နောက်ဝါကျ**ကနေ
        check("အဆုံးက အမှတ် ⇒ နောက်ဝါကျ", rst.get(2) == 3, rst)

    print("\n── ၅ဃ · ASR ရဲ့ ပုံစံ မတူညီမှု ──")
    # ⚠️ တကယ့် ဒေတာမှာ ASR က **တစ်မျိုးတည်း မထုတ်ပါ** — 「နံပါတ် ၃」(ဂဏန်း) ·
    #    「နံပါတ်တစ်」(စာလုံး · space မပါ) · 「သုံးချက်」(ရေတွက်စကားလုံး)。
    #    ဂဏန်းချည်း လက်ခံလျှင် rail **လုံးဝ မပေါ်**ပါ (j_61b8c1dd0fb5)。
    mix = S("ဒါပေမဲ့ ဒီတိုင်းတော့ သွားလို့မရပါဘူး။",
            "အဓိက သော့ချက် သုံးချက် ရှိပါတယ်။",
            "နံပါတ်တစ် COE စိတ်ချရတဲ့ Class 1 ကျောင်း ဖြစ်ရပါမယ်။",
            "ဒါမှ ဗီဇာ ရဖို့ သေချာတာပါ။ နံပါတ်နှစ်",
            "ဂျပန်ရောက်တဲ့အထိ တာဝန်ယူပေးတဲ့ အေဂျင်စီ ရွေးရပါမယ်။",
            "နံပါတ် ၃ ကိုယ့်ဘက်က အောင်လက်မှတ် ရှိထားရပါမယ်။")
    rm = RL.find(mix)
    check("ရေတွက်စကားလုံး 「သုံးချက်」 မိသည်", rm is not None and rm[2] == 3, rm)
    if rm:
        ms = RL.starts(mix, rm[0] + 1, rm[2])
        check("ပုံစံ ၃ မျိုးလုံး မိသည်", len(ms) == 3, ms)
        check("「နံပါတ်တစ်」(space မပါ) မိသည်", 1 in ms, ms)
        check("「နံပါတ်နှစ်」 အဆုံးက ⇒ နောက်ဝါကျ", ms.get(2) == 4, ms)
    check("「နံပါတ်တစ်」 ဖယ်သည်",
          RL._strip_mark("နံပါတ်တစ် COE စိတ်ချရတဲ့") == "COE စိတ်ချရတဲ့",
          RL._strip_mark("နံပါတ်တစ် COE စိတ်ချရတဲ့"))

    print("\n── ၆ · ပုံ ဆွဲခြင်း ──")
    im = RL.panel("စမ်းသပ် ခေါင်းစဉ်", ["၁", "၂", "၃"], active=1,
                  accent="#FFE000", W=1920, H=1080)
    check("အရွယ် မှန်သည်", im.size == (1920, 1080), im.size)
    import numpy as np
    a = np.asarray(im)
    al = a[..., 3]
    check("ပွင့်လင်း နောက်ခံ", al[5, 1500] == 0, al[5, 1500])
    # ⚠️ စာသား pill ထဲက မထွက်ရ — pill အကြား ကွာဟချက်ထဲ ဘာမှ မရှိရ
    gap = int((RL.PITCH - RL.PILL_H) * 1080)
    x0, x1 = int(RL.PILL_X * 1920), int((RL.PILL_X + RL.PILL_W) * 1920)
    spill = 0
    for i in range(2):
        y1 = int((RL.PILL_Y0 + i * RL.PITCH) * 1080) + int(RL.PILL_H * 1080)
        spill += (al[y1 + 4:y1 + gap - 6, x0:x1] > 60).sum()
    check("စာသား pill ထဲ ကျန်သည်", spill < 200, spill)
    ys, xs = np.nonzero(al > 40)
    check("ဘယ်ဘက်မှာသာ", xs.max() < 1920 * 0.46, xs.max() / 1920)

    print()
    if FAILED:
        print(f"  ✗ ကျသည် {len(FAILED)}: {FAILED}")
        return 1
    print("  ✓ အားလုံး အောင်")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
